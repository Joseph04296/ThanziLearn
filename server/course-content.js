const flattenLessons = course => {
  const out = [];
  for (const m of course.modules) {
    if (m.type !== 'module') continue;
    for (const s of m.sections) {
      const bullets = (s.bullets || []).map(b => '• ' + b).join('\n');
      out.push({
        title: s.title,
        body: bullets ? s.body + '\n\n' + bullets : s.body,
        duration_min: s.duration_min || 2,
      });
    }
  }
  return out;
};

const courses = [safeMedication, tbBasics, aiHealthcare].map(c => {
  const assessment = c.modules.find(m => m.type === 'assessment');
  return {
    title: c.title,
    category: c.category,
    description: c.description,
    durationLabel: c.durationLabel,
    skills: c.skills,
    modules: c.modules,
    lessons: flattenLessons(c),
    questions: assessment.questions,
  };
});

